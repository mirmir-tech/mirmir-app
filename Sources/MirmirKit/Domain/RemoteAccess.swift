import Foundation

/// What a remote API key may do on a server's TLS listener.
public enum RemoteKeyScope: Hashable, Sendable, CaseIterable {
    /// Chat, embeddings, model lists, telemetry and activity.
    case use
    /// Everything in `use`, plus managing models and settings.
    case control

    public var label: String {
        switch self {
        case .use: "Use"
        case .control: "Control"
        }
    }

    public var summary: String {
        switch self {
        case .use: "Chat, embeddings, model lists and monitoring."
        case .control: "Use, plus loading, downloading and removing models and changing settings."
        }
    }
}

public enum CertificateSource: Hashable, Sendable {
    /// Generated by the server; clients pin its fingerprint.
    case selfSigned
    /// Configured by the operator, typically issued by a CA.
    case configured
}

public struct RemoteListener: Hashable, Sendable {
    public let address: String
    public let fingerprint: CertificateFingerprint?
    public let certificate: CertificateSource?
}

public struct RemoteKey: Hashable, Sendable, Identifiable {
    public let id: String
    public let name: String
    /// `nil` for a scope this app does not know.
    public let scope: RemoteKeyScope?
    /// `mmk_<id>`, the public part shown in lists.
    public let displayPrefix: String
    public let createdAt: Date
    public let lastUsedAt: Date?
}

public struct RemoteClient: Hashable, Sendable, Identifiable {
    public let keyID: String
    public let keyName: String
    public let scope: RemoteKeyScope?
    /// Empty when the server does not know the peer.
    public let peerAddress: String
    public let firstSeen: Date
    public let lastSeen: Date
    public let requests: UInt64

    public var id: String { "\(keyID)@\(peerAddress)" }
}

/// Remote access of the connected server, as `GetRemoteAccess` reports it.
public struct RemoteAccessStatus: Hashable, Sendable {
    /// The configured listen address; `nil` when remote access is off.
    public let bind: String?
    /// Present while the listener runs.
    public let listener: RemoteListener?
    /// Why a configured listener is not running.
    public let error: String?
    public let keys: [RemoteKey]
    public let clients: [RemoteClient]

    public var isEnabled: Bool { bind != nil }
}

/// A key just created: its value is shown once and never again.
public struct CreatedRemoteKey: Hashable, Sendable {
    public let key: RemoteKey
    public let secret: String
}
